"""Generate the shared fixed-party policy from the checked-in score contexts."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'services/nikke_score'
nikkes = json.loads((ROOT / 'assets/nikkes.json').read_text(encoding='utf-8-sig'))
by_name = {n['name']: n['blablaNameCode'] for n in nikkes}
by_compact_name = {name.replace(' ', ''): code for name, code in by_name.items()}
by_code = {n['blablaNameCode']: n for n in nikkes}
weapons = {'MG': 100202, 'AR': 100102, 'SG': 100402,
           'SR': 100602, 'RL': 100302, 'SMG': 100502}
fixed = {}
option_types = {'atk_pct': ('StatAtk', 2), 'element_bonus': ('IncElementDmg', 4),
                'max_ammo_pct': ('StatAmmoLoad', 2), 'charge_speed_pct': ('StatChargeTime', 2)}
legacy = {t['nameCode']: t for t in json.loads((source / 'targets.json').read_text(encoding='utf-8'))}
selection = json.loads((source / 'collection_team_selection.json').read_text(encoding='utf-8'))
favorite_items = json.loads((source / 'favorite_items.json').read_text(encoding='utf-8'))['items']
assert selection['status'] == 'teams_complete'
targets = []
for target in selection['profiles']:
    codes = target['team']
    assert len(codes) == len(set(codes)) == 5 and target['nameCode'] in codes
    names = [by_code[code]['name'] for code in codes]
    targets.append(dict(key=target['key'], nameCode=target['nameCode'], name=target['name'],
                        weakness=target['weakness'], team=codes, teamNames=names))
    context_growth = {}
    if target['nameCode'] in legacy:
        old = legacy[target['nameCode']]
        context = json.loads((source / 'contexts' / (old['version'] + '.json')).read_text(encoding='utf-8'))
        # A slot-order correction must not also change the four dummy builds.
        old_names = {name.replace(' ', '') for name in context['request']['squad']}
        if old_names == {name.replace(' ', '') for name in names}:
            context_growth = {name.replace(' ', ''): growth for name, growth in context['request']['profile']['chars'].items()}
    # Keep per-target standards: some contexts intentionally use different options.
    party = []
    effects = []
    for name in names:
        code = by_compact_name[name.replace(' ', '')]
        growth = context_growth.get(name.replace(' ', ''), {
            'breakthrough': 3, 'core_enhancement': 0, 'affinity': 30,
            'equip_skills': {'atk_pct': 22.22, 'element_bonus': 88.6,
                             'max_ammo_pct': 129.64, 'charge_speed_pct': 0},
        })
        slot_options = [[] for _ in range(4)]
        for key, (function_type, lines) in option_types.items():
            total = round(growth['equip_skills'][key] * 100)
            if not total:
                continue
            quotient, remainder = divmod(total, lines)
            used_slots = set()
            for line in range(lines):
                effect_id = 900000000 + len(effects)
                effects.append(dict(id=effect_id, function_details=[dict(
                    function_type=function_type,
                    function_value=(quotient + (line < remainder)) * (-1 if function_type == 'StatChargeTime' else 1))]))
                slot = min((i for i in range(4) if i not in used_slots),
                           key=lambda i: (len(slot_options[i]), i))
                used_slots.add(slot)
                slot_options[slot].append(effect_id)
        for options in slot_options:
            assert len(options) <= 3
            options += [0] * (3 - len(options))
        favorite = favorite_items.get(str(code))
        if favorite:
            assert favorite['weapon'] == by_code[code]['weaponType'], (code, favorite)
        item = dict(tid=favorite['tid'], level=favorite['level']) if favorite else dict(
            tid=weapons[by_code[code]['weaponType']], level=15)
        party.append(dict(name_code=code, grade=growth['breakthrough'], core=growth['core_enhancement'],
                          bondLevel=growth['affinity'], skills=dict(skill1=10, skill2=10, burst=10),
                          favoriteItem=item,
                          harmonyCube=dict(tid=1000303, level=15),
                          growthDataQuality=dict(schemaVersion=1, complete=True),
                          equipment=[dict(slot=slot, tier=10, level=5, corporationType=0,
                                          overloadOptions=slot_options[i])
                                     for i, slot in enumerate(['head', 'torso', 'arm', 'leg'])]))
    fixed[target['key']] = dict(characters=party, stateEffects=effects)
(ROOT / 'functions/nikkeScoreTargets.json').write_text(
    json.dumps(targets, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(ROOT / 'functions/nikkeScoreStandards.json').write_text(
    json.dumps(fixed, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
dart = '// Generated by tools/build_partner_score_targets.py.\n'
dart += '''class NikkeScoreProfile {
  const NikkeScoreProfile(this.nameCode, this.weakness, this.teamNames);
  final int nameCode;
  final String weakness;
  final List<String> teamNames;
  String get key => '$nameCode:$weakness';
  String get elementName => const {'fire': '작열', 'iron': '철갑', 'electric': '전격', 'wind': '풍압', 'water': '수냉'}[weakness]!;
}
const nikkeScoreProfiles = <String, NikkeScoreProfile>{
'''
for target in targets:
    dart += f"  '{target['key']}': NikkeScoreProfile({target['nameCode']}, '{target['weakness']}', {json.dumps(target['teamNames'], ensure_ascii=False)}),\n"
dart += '};\n'
(ROOT / 'lib/data/nikke_score_targets.dart').write_text(dart, encoding='utf-8')
